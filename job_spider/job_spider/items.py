"""
JobSpider · 数据字段定义模块 (兼容 Scrapy 2.16)

定义BOSS直聘招聘职位信息的所有Item字段。
字段设计原则：
    1. 全部字段均可在职位搜索列表页的渲染DOM中直接提取，无需请求详情页
    2. 字段命名语义化、全小写+下划线，符合Python及Scrapy命名惯例
    3. 适量冗余（recruiter_*、publish_time），为后续分析留余地
"""

import scrapy


class JobSpiderItem(scrapy.Item):
    """
    BOSS直聘招聘信息 Item

    每条 Item 实例对应一条招聘记录。所有字段均为 scrapy.Field()，
    底层是 Python dict，可直接用于 CSV 序列化。
    """

    # =========================================================================
    # 职位基本信息
    # =========================================================================
    # 职位名称 — 例如 "Python后端开发工程师"
    job_name = scrapy.Field()
    # 薪资范围（原始文案） — 例如 "15k-25k"、"20K-40K·16薪"
    salary = scrapy.Field()
    # 职位详情页完整URL — 例如 "https://www.zhipin.com/job_detail/xxx.html"
    job_url = scrapy.Field()

    # =========================================================================
    # 公司信息
    # =========================================================================
    # 公司全称 — 例如 "北京字节跳动科技有限公司"
    company_name = scrapy.Field()
    # 公司所属行业 — 例如 "移动互联网"、"计算机软件"、"在线教育"
    industry = scrapy.Field()
    # 公司规模 — 例如 "500-999人"、"10000人以上"、"20-99人"
    company_scale = scrapy.Field()

    # =========================================================================
    # 工作地点
    # =========================================================================
    # 城市 — 例如 "北京"、"上海"、"深圳"
    city = scrapy.Field()
    # 区域/商圈 — 例如 "朝阳区·望京"、"浦东新区·张江"
    district = scrapy.Field()

    # =========================================================================
    # 任职要求
    # =========================================================================
    # 经验要求 — 例如 "3-5年"、"经验不限"、"应届生"
    experience = scrapy.Field()
    # 学历要求 — 例如 "本科"、"硕士"、"大专"、"学历不限"
    education = scrapy.Field()

    # =========================================================================
    # 补充信息（列表页有时可额外获取）
    # =========================================================================
    # 招聘者昵称 — 例如 "王经理"、"李先生"
    recruiter_name = scrapy.Field()
    # 招聘者职位 — 例如 "HR"、"技术总监"
    recruiter_title = scrapy.Field()
    # 职位发布时间/活跃状态 — 例如 "刚刚活跃"、"3天内发布"
    publish_time = scrapy.Field()
